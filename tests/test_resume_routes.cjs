const assert = require('node:assert/strict');
const {route, resumeDestination} = require('../zhihuishu-mastery.user.js');
const host = 'https://ai-smart-course-student-pro.zhihuishu.com';
const exam = 'https://studentexamcomh5.zhihuishu.com/studentReviewTestOrExam/17/1/1/1000000000000000001/name?point=1&pointId=31&classId=200001&examPaperId=801';
const task = {course:'1000000000000000001', cls:'200001', queue:[{point:'31'}], index:0, phase:'answering', examKey:'801:17', examUrl:exam};
const home = `${host}/singleCourse/knowledgeStudy/${task.course}/${task.cls}`;
const elsewhere = `${host}/learnPage/${task.course}/32/${task.cls}`;
assert.equal(resumeDestination(task, route(home), home).url, exam);
assert.equal(resumeDestination(task, route(elsewhere), elsewhere).url, exam);
assert.equal(resumeDestination(task, {kind:'hub'}, 'https://onlineweb.zhihuishu.com/').url, exam);
const historyURL = resumeDestination({...task, phase:'history'}, route(elsewhere), elsewhere).url;
assert.equal(route(historyURL).kind, 'history');
assert.equal(route(historyURL).point, '31');
assert.equal(JSON.parse(decodeURIComponent(atob(new URL(historyURL).searchParams.get('nodeName')))), '知识点');
assert.equal(resumeDestination({...task, phase:'catalog'}, route(home), home).url, null);
assert.throws(()=>resumeDestination({...task, examUrl:null}, route(home), home), /未找到原试卷/);
assert.throws(()=>resumeDestination(task, {...route(home), course:'2'}, home), /原课程/);
assert.throws(()=>resumeDestination({...task, examUrl:exam.replace('pointId=31','pointId=32')}, route(home), home), /未找到原试卷/);
const submission = resumeDestination({...task, phase:'submitting'}, route(home), home);
assert.equal(submission.phase, 'submitting');
assert.equal(route(submission.url).kind, 'point');
assert.equal(route(submission.url).key, task.examKey);
const preview = `${host}/examPreview/${task.course}/801/17/31/${task.cls}`;
assert.equal(resumeDestination({...task, phase:'submitting'}, route(preview), preview).phase, 'preview');
console.log('Resume routes passed: exact original paper, phase-aware destinations, course/point guards and read-only submission recovery.');
